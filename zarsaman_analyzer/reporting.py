from __future__ import annotations
import csv
import json
from pathlib import Path
from .models import Status


def write_reports(results: list[dict], meta: dict, out_dir: Path, run_id: str) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {}
    p = out_dir / f"analysis_{run_id}.json"
    p.write_text(json.dumps({"meta": meta, "results": results}, ensure_ascii=False, indent=2), encoding="utf-8")
    paths["json"] = p
    p = out_dir / f"analysis_{run_id}.csv"
    with open(p, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["company_id", "name", "status", "mode", "buy", "sell", "provenance", "failure_kind",
                    "state_mode", "reference_diff_pct", "api_url", "notes"])
        for r in results:
            w.writerow([r["company_id"], r["name"], r["status"], r["mode"], r["buy"], r["sell"],
                        r["recipe_provenance"], r["failure_kind"], r["state_mode"], r["reference_diff_pct"],
                        r["api_url"], " | ".join(r["notes"])])
    paths["csv"] = p
    p = out_dir / f"analysis_evidence_{run_id}.csv"
    with open(p, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["company_id", "name", "path", "role", "raw", "unit", "url", "role_evidence", "product_evidence"])
        for r in results:
            for e in r["evidence"]:
                w.writerow([r["company_id"], r["name"], e["path"], e["role"], e["raw"], e["unit"], e["url"],
                            e["role_evidence"], e["product_evidence"]])
    paths["evidence"] = p

    by = {s.value: [r for r in results if r["status"] == s.value] for s in Status}
    L = [f"# Analysis report {run_id}", "",
         f"- State mode: **{meta['state_mode']}**" + ("" if meta["state_mode"] == "LIVE_STATE" else
          "  (NOT live: freshness and reference comparison are unavailable or unreliable)"),
         f"- State detail: {meta.get('state_detail') or '-'}"]
    for t in meta.get("state_diagnosis", []):
        L.append(f"  - hint: {t}")
    L += ["- Browser stage: " + meta.get("browser_stage", "not run"), "",
          "## Summary", ""] + [f"- {k}: {len(v)}" for k, v in by.items()] + [""]
    net = [r for r in results if r["failure_kind"] in ("NETWORK_DNS", "NETWORK_OTHER")]
    L += [f"- Network/DNS failures (not extraction bugs): {len(net)}", ""]
    for status in (Status.READY_FOR_PHP, Status.BASE_ONLY_READY, Status.NEEDS_REVIEW, Status.FAIL, Status.SKIPPED):
        rows = by[status.value]
        if not rows:
            continue
        L += [f"## {status.value} ({len(rows)})", ""]
        for r in rows:
            price = f" buy={r['buy']:,.0f} sell={r['sell']:,.0f}" if r["buy"] and r["sell"] else ""
            L.append(f"- **{r['name']}** (id={r['company_id']}){price} [{r['recipe_provenance']}] "
                     f"{r['failure_kind'] if r['failure_kind'] != 'NONE' else ''} - {'; '.join(r['notes'])[:300]}")
        L.append("")
    p = out_dir / f"REPORT_{run_id}.md"
    p.write_text("\n".join(L), encoding="utf-8")
    paths["report"] = p

    review = [r for r in results if r["status"] in ("NEEDS_REVIEW", "FAIL")]
    P = [f"# PHP review prompt {run_id}", "",
         "Rules: keep explicit buy/sell as given; never add a spread; BASE_ONLY means ONE price only; "
         "unit conversion only when the unit is explicitly established; do not deploy automatically.", ""]
    for r in review:
        P += [f"### {r['name']} (id={r['company_id']}) - {r['status']}", f"- url: `{r['api_url'] or '-'}`",
              f"- notes: {'; '.join(r['notes'])[:400]}", ""]
    p = out_dir / f"PROMPT_FOR_PHP_REVIEW_{run_id}.md"
    p.write_text("\n".join(P), encoding="utf-8")
    paths["prompt"] = p
    return paths


def write_php_recipes(results: list[dict], recipes: dict, cfg, out_dir: Path) -> list[Path]:
    """Proposed, separate from production. A config array, because the production
    run_scrapers.php contract is inline blocks - the integration shape needs your decision."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for r in results:
        if r["status"] not in (Status.READY_FOR_PHP.value, Status.BASE_ONLY_READY.value):
            continue
        rec = recipes.get(r["company_id"])
        if not rec:
            continue
        def q(s): return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"
        sel = ",\n".join(
            f"        ['path' => {q(s['path'])}, 'role' => {q(s['role'])}, 'unit' => {q(s.get('unit'))}]"
            for s in rec["selectors"])
        hdr = ",\n".join(f"        {q(k)} => {q(v)}" for k, v in (rec.get("headers") or {}).items())
        code = f"""<?php
// PROPOSED RECIPE - generated by zarsaman_analyzer. NOT deployed. Review before use.
// company {r['company_id']} {r['name'].replace(chr(10), ' ')} | status {r['status']} | provenance {r['recipe_provenance']}
// Rules: no synthetic spread; BASE_ONLY means a single price; unit factors are explicit.
declare(strict_types=1);
return [
    'company_id' => {r['company_id']},
    'url' => {q(rec['url'])},
    'method' => 'GET',
    'headers' => [
{hdr}
    ],
    'selectors' => [
{sel}
    ],
    'unit_to_toman_factor' => ['toman' => 1.0, 'rial' => 0.1],
    'sanity_range_toman' => [{cfg.sanity_min:.0f}, {cfg.sanity_max:.0f}],
    'timeout_seconds' => 10,
    'repeat_tolerance' => {cfg.stability_tolerance},
    'mode' => {q(r['mode'])},
    'verified_buy' => {r['buy']},
    'verified_sell' => {r['sell']},
];
"""
        p = out_dir / f"company_{r['company_id']}.recipe.php"
        p.write_text(code, encoding="utf-8")
        written.append(p)
    return written
